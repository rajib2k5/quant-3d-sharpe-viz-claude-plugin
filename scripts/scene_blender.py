"""Write a self-contained Blender (bpy) script that builds the Sharpe skyline.

Usage: python scene_blender.py out/screen_result.json [--out out/skyline_bpy.py] [--chunk-bytes 40000]

The generated script needs nothing but Blender: run it with ``blender --python
out/skyline_bpy.py`` or send its text to a Blender MCP ``execute_blender_code`` call.
Arguments after ``--`` are the script's own: ``-- --render PATH.png`` also renders a still
(headless-safe, e.g. ``blender -b --factory-startup --python out/skyline_bpy.py -- --render
out/skyline.png``; render_skyline.py uses this when Blender or bpy is available). With
--chunk-bytes, the same scene is also written as numbered parts for tools that cap the size
of one call: the data parts stash the JSON in ``bpy.app.driver_namespace`` and the last part
builds the scene. Visual encoding is described in skyline_common.py.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from skyline_common import build_scene, load_result

DATA_KEY = "_sharpe_skyline_json"
INLINE_DATA = "DATA = json.loads(__SKYLINE_JSON__)"
STASHED_DATA = f"DATA = json.loads(bpy.app.driver_namespace.pop({DATA_KEY!r}))"

BUILDER = r'''# Sharpe Observatory skyline: generated by scene_blender.py. Not investment advice.
# Towers: height = annualized Sharpe; colour = FF3 alpha t-stat (gray -> blue -> gold);
# glowing + labelled = top __TOP_N__; red translucent plane = expected best-of-N Sharpe under a
# zero-alpha null (necessary, not sufficient; the skill test is DSR >= 0.95).
import argparse
import json
import math
import os
import sys

import bpy
from mathutils import Vector

__DATA_LINE__

PREFIX = "Skyline_"
COLLECTION_NAME = "SharpeSkyline"
FRAMES_PER_WINDOW = 48
RENDER_SIZE = (1600, 1000)
RENDER_SAMPLES = 64


def script_args(argv):
    parser = argparse.ArgumentParser(prog="skyline_bpy.py", description="Build the Sharpe skyline; optionally render it.")
    parser.add_argument("--render", metavar="PATH.png", help="render a still to this PNG after building")
    return parser.parse_args(argv[argv.index("--") + 1:] if "--" in argv else [])


def enum_ids(rna, prop):
    return [item.identifier for item in rna.properties[prop].enum_items]


def set_enum(target, prop, preferred):
    # Enum identifiers differ between Blender versions, so read the valid ones first.
    if prop not in target.bl_rna.properties:
        return None
    available = enum_ids(target.bl_rna, prop)
    for value in preferred:
        if value in available:
            setattr(target, prop, value)
            return value
    return None


def pick(available, preferred):
    return next((v for v in preferred if v in available), available[0])


def srgb_to_linear(c):
    return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4


def rgba(rgb, alpha=1.0):
    return tuple(srgb_to_linear(c) for c in rgb) + (alpha,)


def socket(node, *names):
    for name in names:
        for s in node.inputs:
            if s.identifier == name or s.name == name:
                return s
    return None


def principled(mat):
    mat.use_nodes = True
    return next(n for n in mat.node_tree.nodes if n.type == "BSDF_PRINCIPLED")


def make_material(name, rgb, emission=0.0, alpha=1.0):
    mat = bpy.data.materials.new(PREFIX + name)
    bsdf = principled(mat)
    socket(bsdf, "Base Color").default_value = rgba(rgb)
    mat.diffuse_color = rgba(rgb, alpha)
    if emission > 0.0:
        emit = socket(bsdf, "Emission Color", "Emission")
        strength = socket(bsdf, "Emission Strength")
        if emit is not None:
            emit.default_value = rgba(rgb)
        if strength is not None:
            strength.default_value = emission
    if alpha < 1.0:
        socket(bsdf, "Alpha").default_value = alpha
        try:
            set_enum(mat, "surface_render_method", ["BLENDED"])
            set_enum(mat, "blend_method", ["BLEND"])
            set_enum(mat, "shadow_method", ["NONE"])
        except (AttributeError, TypeError):
            pass
    return mat


def clear_previous():
    coll = bpy.data.collections.get(COLLECTION_NAME)
    if coll is not None:
        for obj in list(coll.objects):
            bpy.data.objects.remove(obj, do_unlink=True)
        bpy.data.collections.remove(coll)
    for pool in (bpy.data.meshes, bpy.data.curves, bpy.data.cameras, bpy.data.lights, bpy.data.materials):
        for block in list(pool):
            if block.name.startswith(PREFIX) and block.users == 0:
                pool.remove(block)


def link(obj, coll):
    coll.objects.link(obj)
    return obj


def box_mesh(name, size):
    h = size / 2.0
    verts = [(-h, -h, 0), (h, -h, 0), (h, h, 0), (-h, h, 0), (-h, -h, 1), (h, -h, 1), (h, h, 1), (-h, h, 1)]
    faces = [(0, 3, 2, 1), (4, 5, 6, 7), (0, 1, 5, 4), (1, 2, 6, 5), (2, 3, 7, 6), (3, 0, 4, 7)]
    mesh = bpy.data.meshes.new(PREFIX + name)
    mesh.from_pydata(verts, [], faces)
    mesh.update()
    return mesh


def plane_mesh(name, width, depth):
    w, d = width / 2.0, depth / 2.0
    mesh = bpy.data.meshes.new(PREFIX + name)
    mesh.from_pydata([(-w, -d, 0), (w, -d, 0), (w, d, 0), (-w, d, 0)], [], [(0, 1, 2, 3)])
    mesh.update()
    return mesh


def text_object(name, body, size, location, rotation, mat, coll):
    curve_types = [i.identifier for i in bpy.types.BlendDataCurves.bl_rna.functions["new"].parameters["type"].enum_items]
    curve = bpy.data.curves.new(PREFIX + name, type=pick(curve_types, ["FONT"]))
    curve.body = body
    curve.size = size
    set_enum(curve, "align_x", ["CENTER"])
    obj = link(bpy.data.objects.new(PREFIX + name, curve), coll)
    obj.location = location
    obj.rotation_euler = rotation
    obj.data.materials.append(mat)
    return obj


def facing_yaw(src, cam):
    return math.atan2(cam.x - src.x, -(cam.y - src.y))


def build():
    clear_previous()
    scene = bpy.context.scene
    coll = bpy.data.collections.new(COLLECTION_NAME)
    scene.collection.children.link(coll)

    windows = DATA["windows"]
    animate = len(windows) > 1
    frame_of = {w: 1 + i * FRAMES_PER_WINDOW for i, w in enumerate(windows)}
    width, depth = DATA["extent"]["width"], DATA["extent"]["depth"]
    span = max(width, depth, 8.0)
    target = Vector((0.0, 0.0, 3.0))
    cam_loc = Vector((0.45 * span, -1.15 * span, 0.8 * span))

    label_mat = make_material("Label", (0.95, 0.95, 0.95), emission=1.0)
    for sector in DATA["sectors"]:
        text_object("Sector_" + sector["name"], sector["name"], 0.45,
                    (sector["x"], sector["y"], 0.02), (0.0, 0.0, 0.0), label_mat, coll)

    for tower in DATA["towers"]:
        glow = 1.5 if tower["top"] else 0.0
        mat = make_material("Mat_" + tower["ticker"], tower["color"], emission=glow)
        obj = link(bpy.data.objects.new(PREFIX + tower["ticker"], box_mesh(tower["ticker"], DATA["tower_size"])), coll)
        obj.data.materials.append(mat)
        obj.location = (tower["x"], tower["y"], 0.0)
        obj["sr_ann"] = json.dumps(tower["sr_ann"])
        obj["dsr"] = -1.0 if tower["dsr"] is None else tower["dsr"]
        label = None
        if tower["top"]:
            yaw = facing_yaw(Vector((tower["x"], tower["y"], 0.0)), cam_loc)
            label = text_object("Label_" + tower["ticker"], tower["ticker"], 0.42,
                                (tower["x"], tower["y"], 0.0), (math.pi / 2, 0.0, yaw), label_mat, coll)
        for w in windows:
            h = tower["height"][w]
            obj.scale = (1.0, 1.0, h if abs(h) > 1e-4 else 1e-4)
            if label is not None:
                label.location.z = max(h, 0.0) + 0.35
            if animate:
                obj.keyframe_insert(data_path="scale", index=2, frame=frame_of[w])
                if label is not None:
                    label.keyframe_insert(data_path="location", index=2, frame=frame_of[w])

    luck_mat = make_material("LuckHorizon", DATA["luck_rgb"], emission=0.3, alpha=0.35)
    plane = link(bpy.data.objects.new(PREFIX + "LuckHorizon", plane_mesh("LuckHorizon", width + 3.0, depth + 3.0)), coll)
    plane.data.materials.append(luck_mat)
    plane["luck_horizon_ann"] = json.dumps(DATA["luck_horizon_ann"])
    for w in windows:
        plane.location = (0.0, 0.0, DATA["luck_height"][w])
        if animate:
            plane.keyframe_insert(data_path="location", index=2, frame=frame_of[w])

    cam_data = bpy.data.cameras.new(PREFIX + "Camera")
    cam_data.lens = 35.0
    camera = link(bpy.data.objects.new(PREFIX + "Camera", cam_data), coll)
    camera.location = cam_loc
    camera.rotation_euler = (target - cam_loc).to_track_quat("-Z", "Y").to_euler()
    scene.camera = camera

    light_types = enum_ids(bpy.types.Light.bl_rna, "type")
    sun_data = bpy.data.lights.new(PREFIX + "Sun", type=pick(light_types, ["SUN"]))
    sun_data.energy = 3.0
    sun = link(bpy.data.objects.new(PREFIX + "Sun", sun_data), coll)
    sun.rotation_euler = (math.radians(50.0), 0.0, math.radians(30.0))

    try:
        world = scene.world or bpy.data.worlds.new(PREFIX + "World")
        scene.world = world
        world.use_nodes = True
        background = next(n for n in world.node_tree.nodes if n.type == "BACKGROUND")
        background.inputs[0].default_value = (0.01, 0.012, 0.02, 1.0)
    except (AttributeError, StopIteration, TypeError):
        pass
    try:
        scene.eevee.use_bloom = True
    except AttributeError:
        pass

    if animate:
        scene.frame_start = 1
        scene.frame_end = frame_of[windows[-1]] + FRAMES_PER_WINDOW // 2
    scene.frame_set(frame_of[DATA["window"]])
    return coll


def use_engine(scene):
    # scene.render.engine's enum under-reports in some builds, so try assignments instead.
    for engine in ("CYCLES", "BLENDER_WORKBENCH"):
        try:
            scene.render.engine = engine
            return engine
        except TypeError:
            continue
    return scene.render.engine


def render(path, coll):
    scene = bpy.context.scene
    for obj in scene.objects:
        if obj.name not in coll.objects:
            obj.hide_render = True  # e.g. the factory-startup cube, camera and light
    engine = use_engine(scene)
    if engine == "CYCLES":
        try:
            set_enum(scene.cycles, "device", ["CPU"])
            scene.cycles.samples = RENDER_SAMPLES
            scene.cycles.use_denoising = bool(getattr(bpy.app.build_options, "openimagedenoise", False))
        except AttributeError:
            pass
    else:
        try:
            set_enum(scene.display.shading, "light", ["STUDIO"])
            set_enum(scene.display.shading, "color_type", ["MATERIAL"])
        except AttributeError:
            pass
    try:
        scene.world.color = (0.01, 0.012, 0.02)
    except AttributeError:
        pass
    scene.render.resolution_x, scene.render.resolution_y = RENDER_SIZE
    scene.render.resolution_percentage = 100
    set_enum(scene.render.image_settings, "file_format", ["PNG"])
    scene.render.filepath = os.path.abspath(path)
    bpy.ops.render.render(write_still=True)
    print("Sharpe skyline rendered with %s to %s" % (engine, scene.render.filepath))


ARGS = script_args(sys.argv)
SKYLINE = build()
print("Sharpe skyline built: %d towers, luck plane at annualized Sharpe %s for window %s" % (
    len(DATA["towers"]), DATA["luck_horizon_ann"][DATA["window"]], DATA["window"]))
if ARGS.render:
    render(ARGS.render, SKYLINE)
'''


def render_script(scene: dict, stashed: bool = False) -> str:
    data_line = STASHED_DATA if stashed else INLINE_DATA.replace("__SKYLINE_JSON__", repr(json.dumps(scene, separators=(",", ":"))))
    return BUILDER.replace("__TOP_N__", str(scene["top_n"])).replace("__DATA_LINE__", data_line)


def render_chunks(scene: dict, chunk_bytes: int) -> list[str]:
    """Data parts that rebuild the JSON in bpy.app.driver_namespace, then the builder."""
    payload = json.dumps(scene, separators=(",", ":"))
    pieces = [payload[i:i + chunk_bytes] for i in range(0, len(payload), chunk_bytes)]
    parts = []
    for i, piece in enumerate(pieces):
        prior = f"ns.get({DATA_KEY!r}, '') + " if i else ""
        parts.append(f"import bpy\nns = bpy.app.driver_namespace\nns[{DATA_KEY!r}] = {prior}{piece!r}\n")
    parts.append(render_script(scene, stashed=True))
    return parts


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate a self-contained bpy skyline script.")
    parser.add_argument("result", type=Path, help="screen_result.json from screen.py")
    parser.add_argument("--out", type=Path, help="default: skyline_bpy.py next to the result")
    parser.add_argument("--chunk-bytes", type=int, help="also write numbered parts with at most this much JSON each")
    args = parser.parse_args(argv)

    scene = build_scene(load_result(args.result))
    out = args.out or args.result.parent / "skyline_bpy.py"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render_script(scene), encoding="utf-8")
    print(f"wrote {out} ({out.stat().st_size} bytes, {len(scene['towers'])} towers)")
    if args.chunk_bytes:
        if args.chunk_bytes < 1:
            parser.error("--chunk-bytes must be positive")
        for i, part in enumerate(render_chunks(scene, args.chunk_bytes), start=1):
            path = out.with_name(f"{out.stem}_part{i:02d}.py")
            path.write_text(part, encoding="utf-8")
            print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
